"""Find and replace text across the runs of a paragraph.

PowerPoint splits the text of a paragraph into runs (`a:r`) wherever it records something about
part of it, often only proofing state, so one visible word can be spread over several runs. The
classes here match against the paragraph's text instead, and map each match back to the runs it
touches.

A match never crosses a line break, a field or a paragraph: those split a paragraph's runs into
segments (see `CT_TextParagraph.run_segments()`) and each segment is searched on its own.

On a slide, the text searched is that of every shape with a text frame, group members and table
cells included, and of the slide's notes slide when it has one (see `iter_slide_text_frames()`).
Layouts, masters, charts, SmartArt and comments are not searched.
"""

from __future__ import annotations

import dataclasses
import itertools
import re
from bisect import bisect_right
from typing import TYPE_CHECKING, Iterable, Iterator, NamedTuple, Union, cast

from pptx.exc import InvalidTypeError, InvalidValueError
from pptx.oxml.text import CT_RegularTextRun
from pptx.shapes.autoshape import Shape
from pptx.shapes.graphfrm import GraphicFrame
from pptx.shapes.group import GroupShape
from pptx.text.text import TextFrame, _Run

if TYPE_CHECKING:
    from pptx.opc.package import XmlPart
    from pptx.oxml.text import CT_TextParagraph
    from pptx.shapes.base import BaseShape
    from pptx.slide import Slide
    from pptx.text.text import _Paragraph

#: A search pattern: a `str`, literal unless `regex=True`, or a compiled regular expression.
Pattern = Union[str, re.Pattern[str]]


@dataclasses.dataclass(frozen=True)
class TextMatch:
    """One occurrence of a pattern in the text of a paragraph.

    `paragraph.text[start:end] == text` always holds. Immutable.
    """

    paragraph: _Paragraph
    """The |_Paragraph| the match is in."""

    paragraph_index: int
    """Index of `paragraph` in its text frame; 0 when searching a single paragraph."""

    start: int
    """Offset of the first matched character in `paragraph.text`."""

    end: int
    """Offset just past the last matched character in `paragraph.text`."""

    text: str
    """The matched text."""

    runs: tuple[_Run, ...]
    """The runs that hold at least one matched character, in document order."""

    shape: BaseShape | None = None
    """The shape whose text frame holds the match.

    Set by `Slide.find_text()` and `Presentation.find_text()`; the graphic frame for a match in a
    table cell. |None| when searching a text frame or a paragraph directly.
    """


class TextChar(NamedTuple):
    """One character of a paragraph's text, as generated by `iter_chars()`."""

    char: str
    """The character. A line break reads as `"\\v"`."""

    paragraph_index: int
    """Index of the paragraph in its text frame; 0 when iterating a single paragraph."""

    offset: int
    """Offset of the character in the paragraph's text."""

    run: _Run | None
    """The run that holds the character; |None| for a line break or the text of a field."""


def compile_pattern(pattern: Pattern, regex: bool) -> re.Pattern[str]:
    """Return `pattern` compiled, as the find and replace methods interpret it.

    A `str` is a literal unless `regex` is True; a compiled pattern implies `regex` and keeps its
    flags. An empty literal raises |InvalidValueError| because it would match everywhere.
    """
    if isinstance(pattern, re.Pattern):
        if not isinstance(pattern.pattern, str):
            raise InvalidTypeError("pattern must be a str or a compiled str pattern, got bytes")
        return cast("re.Pattern[str]", pattern)
    if not isinstance(pattern, str):
        raise InvalidTypeError(
            f"pattern must be a str or a compiled pattern, got {type(pattern).__name__}"
        )
    if not regex:
        if not pattern:
            raise InvalidValueError("pattern must not be empty")
        return re.compile(re.escape(pattern))
    try:
        return re.compile(pattern)
    except re.error as e:
        raise InvalidValueError(f"pattern is not a valid regular expression: {e}") from e


class _Hit(NamedTuple):
    """A match in one paragraph, located in the runs of its segment."""

    start: int
    """Offset into the paragraph text."""
    end: int
    match: re.Match[str]
    runs: list[CT_RegularTextRun]
    """The segment's runs from the one holding the first character to the one holding the last,
    including any empty run between them."""
    run_start: int
    """Offset of the match in the first run's text."""
    run_end: int
    """Offset of the end of the match in the last run's text."""


def _iter_hits(p: CT_TextParagraph, compiled: re.Pattern[str]) -> Iterator[_Hit]:
    """Generate each non-empty match of `compiled` in `p`, in document order."""
    for seg_start, runs in p.run_segments():
        texts = [r.text for r in runs]
        # -- bounds[i] is where run i starts in the segment text; bounds[-1] is its length --
        bounds = [0, *itertools.accumulate(len(t) for t in texts)]
        for m in compiled.finditer("".join(texts)):
            start, end = m.span()
            if start == end:
                continue
            # -- bisect_right skips empty runs, so `first` and `last` hold matched text --
            first = bisect_right(bounds, start) - 1
            last = bisect_right(bounds, end - 1) - 1
            yield _Hit(
                seg_start + start,
                seg_start + end,
                m,
                runs[first : last + 1],
                start - bounds[first],
                end - bounds[last],
            )


class TextFinder:
    """Finds the matches of one pattern, compiled once, in paragraphs, text frames or slides."""

    def __init__(self, pattern: Pattern, *, regex: bool = False):
        self._compiled = compile_pattern(pattern, regex)

    def find_in(
        self, paragraphs: Iterable[_Paragraph], shape: BaseShape | None = None
    ) -> list[TextMatch]:
        """Every match in `paragraphs`, in document order; `paragraph_index` counts from 0.

        Each match's `shape` is `shape`. Does not change the XML.
        """
        matches: list[TextMatch] = []
        for idx, paragraph in enumerate(paragraphs):
            p = paragraph._p  # pyright: ignore[reportPrivateUsage]
            for hit in _iter_hits(p, self._compiled):
                last = len(hit.runs) - 1
                runs = tuple(
                    _Run(r, paragraph) for k, r in enumerate(hit.runs) if k in (0, last) or r.text
                )
                matches.append(
                    TextMatch(paragraph, idx, hit.start, hit.end, hit.match.group(), runs, shape)
                )
        return matches

    def find_in_slide(self, slide: Slide) -> list[TextMatch]:
        """Every match in the text of `slide`, as `iter_slide_text_frames()` walks it."""
        return [
            match
            for shape, text_frame in iter_slide_text_frames(slide)
            for match in self.find_in(text_frame.paragraphs, shape)
        ]


class TextReplacer:
    """Replaces `old` with `new` in paragraphs, with one `count` shared over every call.

    The text frame, slide and presentation `replace()` methods each use one replacer, so `count`
    limits the replacements over the whole frame, slide or presentation, in document order.
    """

    def __init__(self, old: Pattern, new: str, *, count: int | None = None, regex: bool = False):
        self._compiled = compile_pattern(old, regex)
        if not isinstance(new, str):
            raise InvalidTypeError(f"new must be a str, got {type(new).__name__}")
        if count is not None and count < 0:
            raise InvalidValueError(f"count must be None or at least 0, got {count}")
        self._new = new
        self._expand = regex or not isinstance(old, str)
        self._remaining = count
        self.replaced = 0
        """Number of replacements made so far."""

    @property
    def done(self) -> bool:
        """True once `count` replacements have been made."""
        return self._remaining == 0

    def replace_in(self, paragraphs: Iterable[_Paragraph]) -> int:
        """Replace in each of `paragraphs` in turn; return the number of replacements made."""
        before = self.replaced
        for paragraph in paragraphs:
            if self.done:
                break
            self._replace_in_paragraph(paragraph)
        return self.replaced - before

    def replace_in_slide(self, slide: Slide) -> int:
        """Replace in the text of `slide`, as `iter_slide_text_frames()` walks it."""
        before = self.replaced
        for _, text_frame in iter_slide_text_frames(slide):
            if self.done:
                break
            self.replace_in(text_frame.paragraphs)
        return self.replaced - before

    def _replace_in_paragraph(self, paragraph: _Paragraph) -> None:
        p = paragraph._p  # pyright: ignore[reportPrivateUsage]
        hits = list(itertools.islice(_iter_hits(p, self._compiled), self._remaining))
        # -- right to left, so the offsets of the earlier hits stay valid --
        for hit in reversed(hits):
            new = hit.match.expand(self._new) if self._expand else self._new
            self._apply(hit, new, paragraph)
        self.replaced += len(hits)
        if self._remaining is not None:
            self._remaining -= len(hits)

    @staticmethod
    def _apply(hit: _Hit, new: str, paragraph: _Paragraph) -> None:
        """Replace the text of `hit` with `new`, which takes the formatting of the first run."""
        first, last = hit.runs[0], hit.runs[-1]
        if first is last:
            first.splice(hit.run_start, hit.run_end, new)
        else:
            first.splice(hit.run_start, len(first.text), new)
            for r in hit.runs[1:-1]:
                _remove_run(r, paragraph)
            last.splice(0, hit.run_end, "")
            if not last.text:
                _remove_run(last, paragraph)
        if not first.text:
            _remove_run(first, paragraph)


def _remove_run(r: CT_RegularTextRun, paragraph: _Paragraph) -> None:
    """Remove `r`, first dropping any relationship (e.g. a hyperlink) only it refers to.

    `XmlPart.drop_rel()` drops a relationship only while fewer than two references to it remain,
    so it must be called while `r` still counts as one of them.
    """
    rIds = cast("list[str]", r.xpath(".//@r:id"))
    if rIds:
        part = cast("XmlPart", paragraph.part)
        for rId in rIds:
            if rId in part.rels:
                part.drop_rel(rId)
    p = r.getparent()
    assert p is not None
    p.remove(r)


def iter_paragraph_chars(paragraph: _Paragraph, paragraph_index: int) -> Iterator[TextChar]:
    """Generate a |TextChar| for each character of `paragraph.text`."""
    offset = 0
    for elm in paragraph._p.content_children:  # pyright: ignore[reportPrivateUsage]
        run = _Run(elm, paragraph) if isinstance(elm, CT_RegularTextRun) else None
        for char in elm.text:
            yield TextChar(char, paragraph_index, offset, run)
            offset += 1


def iter_slide_text_frames(slide: Slide) -> Iterator[tuple[BaseShape, TextFrame]]:
    """Generate `(shape, text_frame)` for each text frame on `slide`, then on its notes slide.

    Shapes go in shape-tree order, each group's members in place of the group, and each table's
    cells row by row (the graphic frame is their `shape`). The notes slide's shapes follow, when
    the slide has a notes slide; none is created. A shape or cell with no `txBody` is skipped,
    so walking the slide never adds one.
    """
    yield from _iter_shapes_text_frames(slide.shapes)
    if slide.has_notes_slide:
        yield from _iter_shapes_text_frames(slide.notes_slide.shapes)


def _iter_shapes_text_frames(
    shapes: Iterable[BaseShape],
) -> Iterator[tuple[BaseShape, TextFrame]]:
    for shape in shapes:
        if isinstance(shape, GroupShape):
            yield from _iter_shapes_text_frames(shape.shapes)
        elif isinstance(shape, GraphicFrame) and shape.has_table:
            for cell in shape.table.iter_cells():
                txBody = cell._tc.txBody  # pyright: ignore[reportPrivateUsage]
                if txBody is not None:
                    yield shape, TextFrame(txBody, cell)
        elif isinstance(shape, Shape):
            txBody = shape._sp.txBody  # pyright: ignore[reportPrivateUsage]
            if txBody is not None:
                yield shape, TextFrame(txBody, shape)
